/** «پایان نامه» جدا → «پایان‌نامه» (پیش از قواعد پسوند، تا «پایان نامه‌ها» هم درست شود) */
const THESIS_WORD_SEPARATED = /پایان[ \t]+نامه/g;

/**
 * جایگزینی یک واژه به‌صورت کامل (نه داخل واژه‌ی دیگر)؛
 * مرز واژه با حروف فارسی و نیم‌فاصله سنجیده می‌شود.
 */
function replaceWholeWord(text: string, word: string, replacement: string): string {
  const pattern = new RegExp(
    `(^|[^${PERSIAN_LETTER}${ZWNJ}])(${word})(?![${PERSIAN_LETTER}${ZWNJ}])`,
    'g',
  );
  return text.replace(pattern, `$1${replacement}`);
}

/**
 * اصلاح فاصله‌گذاری یک رشته‌ی فارسی.
 * ورودی دست‌نخورده می‌ماند اگر فقط نویسه‌های غیرفارسی داشته باشد.
 */
export function normalizePersianSpacing(input: string): string {
  let text = String(input ?? '');
  if (!text) return '';

  // ۱) فاصله‌های یونیکد → فاصله‌ی معمولی؛ نویسه‌های نامرئیِ میان کلمات
  //    به فاصله تبدیل و در بقیه‌ی موارد حذف می‌شوند (وگرنه کلمات به هم می‌چسبند)
  text = text.replace(UNICODE_SPACES, ' ');
  text = text.replace(INVISIBLE_BETWEEN_WORDS, '$1 ');
  text = text.replace(ZWJ_BETWEEN_PERSIAN, '$1 ');
  text = text.replace(INVISIBLE_CHARS, '');

  // ۲) یکسان‌سازی «ي/ك» عربی با «ی/ک» فارسی
  text = text.replace(/\u064a/g, '\u06cc').replace(/\u0643/g, '\u06a9');

  // ۳) نیم‌فاصله‌های تکراری و فاصله‌ی اضافی پیش از نیم‌فاصله
  text = text.replace(/\u200c{2,}/g, '\u200c');
  text = text.replace(/[ \t]\u200c/g, '\u200c');

  // ۴) فاصله‌ی جاافتاده پس از نشانه‌های سجاوندی
  text = text.replace(PERSIAN_PUNCT_WITHOUT_SPACE, '$1 ');
  text = text.replace(PUNCT_BEFORE_PERSIAN, '$1 ');
  text = text.replace(CLOSING_BRACKET_WITHOUT_SPACE, '$1 ');
  text = text.replace(OPENING_BRACKET_WITHOUT_SPACE, '$1 ');

  // ۵) چسبیدن حروف فارسی و لاتین/عدد («مدلCIPP»، «CIPPمدل»)
  text = text.replace(PERSIAN_THEN_LATIN, '$1 $2');
  text = text.replace(LATIN_THEN_PERSIAN, '$1 $2');

  // ۶) فاصله‌های افقی تکراری (تورفتگی ابتدای خط حفظ می‌شود)
  text = text.replace(/([^\s])[ \t]{2,}/g, '$1 ');

  return text;
}

/**
 * درست‌نویسی کامل متن فارسی: فاصله‌گذاری + نیم‌فاصله + غلط‌های رایج.
 * روی خروجی مدل زبانی، متن استخراج‌شده و متن گزارش اعمال می‌شود.
 * متن لاتین یا کد (که حرف فارسی ندارد) دست‌نخورده می‌ماند.
 */
export function polishPersianText(input: string): string {
  let text = normalizePersianSpacing(input);
  if (!text) return '';
  // متن بدون حرف فارسی (کد، مسیر فایل، متن لاتین) دست‌نخورده می‌ماند
  if (!/[\u0600-\u06FF]/.test(text)) return text;

  // ۱) حروف عربی → فارسی («ي»، «ى»، «ك»، «ة»)
  text = text
    .replace(/[\u064a\u0649]/g, '\u06cc')
    .replace(/\u0643/g, '\u06a9')
    .replace(/\u0629/g, '\u0647');

  // ۲) نیم‌فاصله‌ی «می/نمی» («می شود» و «میشود» → «می‌شود»)
  text = text.replace(MI_VERB_SEPARATED, `$1$2${ZWNJ}$3`);
  text = text.replace(MI_VERB_GLUED, `$1$2${ZWNJ}$3`);
  text = text.replace(NEGATED_MI_GLUED, `$1نمی${ZWNJ}`);

  // ۳) پسوند جمع («کتاب ها» و «کتابها» → «کتاب‌ها»)
  text = text.replace(THESIS_WORD_SEPARATED, `پایان${ZWNJ}نامه`);
  text = text.replace(PLURAL_SEPARATED, `$1${ZWNJ}$2`);
  text = text.replace(PLURAL_GLUED, (match: string, stem: string, plural: string, suffix?: string) => {
    // واژه‌هایی که «ها» در آن‌ها پسوند جمع نیست («تنها»، «رها»، «بها») دست‌نخورده می‌مانند
    if (PLURAL_EXCEPTIONS.has(match)) return match;
    return `${stem}${ZWNJ}${plural}${suffix ?? ''}`;
  });

  // ۴) پسوندهای صفت‌ساز و ترکیب‌های پرکاربرد
  for (const [spaced, joined] of COMPOUND_SPACED) {
    text = replaceWholeWord(text, spaced, joined);
  }
  text = text.replace(SUPERLATIVE_SEPARATED, `$1${ZWNJ}$2`);
  text = text.replace(COMPARATIVE_SEPARATED, `$1${ZWNJ}$2`);
  text = text.replace(HE_Y_SEPARATED, `$1${ZWNJ}$2`);
  text = text.replace(HE_INDEFINITE_SEPARATED, `$1${ZWNJ}$2`);

  // ۵) غلط‌های املایی/نگارشی پربسامد
  for (const [wrong, right] of WORD_FIXES) {
    text = replaceWholeWord(text, wrong, right);
  }

  // ۶) پاک‌سازی نهایی فاصله‌ها (تورفتگی ابتدای خط حفظ می‌شود)
  text = text.replace(/[ \t]*\u200c[ \t]*/g, ZWNJ);
  text = text.replace(/([^ \t])[ \t]{2,}/g, '$1 ');

  return text;
}

/**
 * اعمال یکسان‌سازی روی یک متن Markdown، بدون دست‌زدن به بلوک‌های کد.
 * هر خط جداگانه پردازش می‌شود تا ساختار Markdown (لیست، جدول، تیتر) حفظ شود.
 *
 * `orthography: true` فقط برای متنِ تولیدشده (گزارش و خروجی مدل) استفاده می‌شود؛
 * متن خود کاربر (پایان‌نامه) فقط از نظر فاصله‌گذاری اصلاح می‌شود تا نوشته‌ی او
 * بازنویسی نشود.
 */
export function polishPersianMarkdown(
  markdown: string,
  options: { orthography?: boolean } = {},
): string {
  const lines = String(markdown ?? '').split('\n');
  let inFence = false;

  return lines
    .map((line) => {
      // مرزهای بلوک کد: ``` یا ~~~
      if (/^\s*(```|~~~)/.test(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return options.orthography ? polishPersianText(line) : normalizePersianSpacing(line);
    })
    .join('\n');
}
